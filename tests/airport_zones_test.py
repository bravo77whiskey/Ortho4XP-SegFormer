# RCKH's runway 09/27 as apt.dat has it: 60 m wide, ~3150 m long.
RCKH = [(60.0, 22.57751686, 120.33486924, 22.57660338, 120.3654979)]
DISTANCES = {19: 1600.0, 18: 4350.0, 17: 14550.0}


def _apt_dat(airports):
    """apt.dat text: {icao: [(width, lat1, lon1, lat2, lon2)]}."""
    lines = ["I", "1200 Generated by test", ""]
    for icao, runways in airports.items():
        lines.append(f"1 10 0 0 {icao} Test airport {icao}")
        for width, lat1, lon1, lat2, lon2 in runways:
            lines.append(
                f"100 {width:.2f} 1 0 0.25 0 2 1 09 {lat1:.8f} {lon1:.8f} 0 0 3 0 0 0 "
                f"27 {lat2:.8f} {lon2:.8f} 0 0 3 0 0 0"
            )
        lines.append("110 1 0.25 0 Taxiway")
        lines.append(f"111 {runways[0][1]:.8f} {runways[0][2]:.8f}")
        lines.append("")
    lines.append("99")
    return "\n".join(lines) + "\n"


def _xplane(tmp, custom=None, global_airports=None):
    """A fake X-Plane folder: one custom pack (listed first) and the global apt.dat."""
    root = Path(tmp) / "X-Plane 12"
    gdir = root / "Global Scenery" / "Global Airports" / "Earth nav data"
    gdir.mkdir(parents=True)
    (gdir / "apt.dat").write_text(_apt_dat(global_airports or {}), encoding="utf-8")
    cs = root / "Custom Scenery"
    cs.mkdir()
    packs = ["I", "1000 Version", "SCENERY", ""]
    if custom:
        pdir = cs / "Airport_Custom" / "Earth nav data"
        pdir.mkdir(parents=True)
        (pdir / "apt.dat").write_text(_apt_dat(custom), encoding="utf-8")
        packs.append("SCENERY_PACK Custom Scenery/Airport_Custom/")
    packs.append("SCENERY_PACK *GLOBAL_AIRPORTS*")
    (cs / "scenery_packs.ini").write_text("\n".join(packs) + "\n", encoding="utf-8")
    return str(root)


def _mean_ring_distance(runways, coords):
    """Mean distance (m) from the runway hull to points along a ring."""
    from shapely.geometry import LineString

    hull, (lat0, lon0, kx, ky) = AZONE.runway_hull(runways)
    ring = LineString(
        [((lon - lon0) * kx, (lat - lat0) * ky) for lat, lon in zip(coords[::2], coords[1::2])]
    )
    n = 400
    return sum(
        hull.distance(ring.interpolate(i / n, normalized=True)) for i in range(n)
    ) / n


class SettingsTest(unittest.TestCase):
    def test_icao_list_is_tolerant(self):
        self.assertEqual(AZONE.parse_icaos(" rckh, RCAY,,RCKH  rcbs"), ["RCKH", "RCAY", "RCBS"])
        self.assertEqual(AZONE.parse_icaos(""), [])

    def test_icao_list_is_tile_only_and_distances_are_global_too(self):
        self.assertIn("airport_zone_icaos", CFGVARS.list_tile_vars)
        self.assertNotIn("global_airport_zone_icaos", CFGVARS.cfg_global_tile_vars)
        self.assertNotIn("global_airport_zone_icaos", CFGVARS.list_global_dsf_vars)
        for zl in AZONE.ZONE_ZLS:
            var = f"airport_zone_zl{zl}_m"
            self.assertIn(var, CFGVARS.list_dsf_vars)
            self.assertIn(CFGVARS.global_prefix + var, CFGVARS.list_global_dsf_vars)
            self.assertEqual(CFGVARS.cfg_tile_vars[var]["default"], DISTANCES[zl])

    def test_tile_icaos_read_from_config(self):
        with tempfile.TemporaryDirectory() as tmp:
            cfg = Path(tmp) / "Ortho4XP_+22+120.cfg"
            cfg.write_text("default_zl=16\nairport_zone_icaos=rckh,RCAY\n", encoding="utf-8")
            self.assertEqual(AZONE.read_tile_icaos(str(cfg)), ["RCKH", "RCAY"])
            self.assertEqual(AZONE.read_tile_icaos(str(Path(tmp) / "missing.cfg")), [])


class RunwayLookupTest(unittest.TestCase):
    def test_highest_priority_pack_wins_and_misses_are_cached(self):
        moved = [(45.0, 22.6, 120.3, 22.6, 120.33)]
        with tempfile.TemporaryDirectory() as tmp:
            xp = _xplane(tmp, custom={"RCKH": moved}, global_airports={"RCKH": RCKH, "RCAY": RCKH})
            cache = str(Path(tmp) / "cache")
            found = AZONE.runways_by_icao(xp, ["RCKH", "RCAY", "ZZZZ"], cache_dir=cache)
            self.assertEqual(set(found), {"RCKH", "RCAY"})
            self.assertAlmostEqual(found["RCKH"][0][0], 45.0)
            self.assertAlmostEqual(found["RCAY"][0][1], RCKH[0][1], places=6)
            # The cache answers without reading apt.dat again.
            gapt = Path(xp) / "Custom Scenery" / "Airport_Custom" / "Earth nav data" / "apt.dat"
            gapt.write_text("", encoding="utf-8")
            again = AZONE.runways_by_icao(xp, ["RCKH", "ZZZZ"], cache_dir=cache)
            self.assertAlmostEqual(again["RCKH"][0][0], 45.0)
            self.assertNotIn("ZZZZ", again)


class RingGeometryTest(unittest.TestCase):
    def test_rings_sit_at_the_configured_distance(self):
        rings = AZONE.airport_rings(RCKH, DISTANCES)
        self.assertEqual([zl for _, zl in rings], [19, 18, 17])
        for coords, zl in rings:
            self.assertEqual(coords[:2], coords[-2:])  # closed ring
            self.assertAlmostEqual(_mean_ring_distance(RCKH, coords), DISTANCES[zl], delta=20)

    def test_zero_distance_leaves_the_ring_out(self):
        rings = AZONE.airport_rings(RCKH, {19: 1600.0, 18: 0.0, 17: 9000.0})
        self.assertEqual([zl for _, zl in rings], [19, 17])

    def test_hull_spans_all_runways(self):
        crossing = RCKH + [(45.0, 22.56, 120.35, 22.59, 120.35)]
        hull, _frame = AZONE.runway_hull(crossing)
        single, _frame = AZONE.runway_hull(RCKH)
        self.assertGreater(hull.area, single.area * 10)


class PlanTest(unittest.TestCase):
    def _plan(self, tiles, icaos_by_tile, runways=None):
        runways = runways if runways is not None else {"RCKH": RCKH}
        log = []
        plan = AZONE.plan_zones(
            tiles,
            lambda lat, lon: (icaos_by_tile.get((lat, lon), []), DISTANCES),
            lambda icaos: {code: runways[code] for code in icaos if code in runways},
            log=log.append,
        )
        return plan, log

    def test_neighbours_in_the_batch_get_the_zones(self):
        # RCKH sits ~0.42 deg from the western edge of +22+120: the 14.5 km
        # ZL17 ring stays inside, so make the airport sit near the edge.
        near_edge = [(60.0, 22.97, 120.85, 22.97, 120.88)]
        tiles = [(22, 120), (23, 120), (22, 121), (21, 120)]
        plan, log = self._plan(tiles, {(22, 120): ["RCKH"]}, {"RCKH": near_edge})
        self.assertEqual([z[1] for z in plan[(22, 120)]], [19, 18, 17])
        self.assertEqual([z[1] for z in plan[(23, 120)]], [18, 17])
        self.assertEqual([z[1] for z in plan[(22, 121)]], [17])
        self.assertNotIn((21, 120), plan)
        self.assertFalse(log)

    def test_neighbours_outside_the_batch_get_nothing(self):
        near_edge = [(60.0, 22.97, 120.85, 22.97, 120.88)]
        plan, _log = self._plan([(22, 120)], {(22, 120): ["RCKH"]}, {"RCKH": near_edge})
        self.assertEqual(set(plan), {(22, 120)})

    def test_airport_listed_in_another_tile_is_skipped(self):
        plan, log = self._plan([(22, 120), (23, 120)], {(23, 120): ["RCKH"]})
        self.assertEqual(plan, {})
        self.assertTrue(any("RCKH is not in tile +23+120" in line for line in log))

    def test_airport_without_runways_is_skipped(self):
        plan, log = self._plan([(22, 120)], {(22, 120): ["ZZZZ"]})
        self.assertEqual(plan, {})
        self.assertTrue(any("ZZZZ" in line for line in log))


class MergeTest(unittest.TestCase):
    def test_airport_zones_beat_coarser_drawn_zones_only(self):
        drawn20 = [[1], 20, "D"]
        drawn18 = [[2], 18, "D"]
        drawn16 = [[3], 16, "D"]
        apt19, apt18, apt17 = [[4], 19, "A"], [[5], 18, "A"], [[6], 17, "A"]
        merged = AZONE.merge_zone_lists([drawn20, drawn18, drawn16], [apt17, apt19, apt18])
        self.assertEqual(merged, [drawn20, apt19, drawn18, apt18, apt17, drawn16])

    def test_no_airport_zones_leaves_drawn_zones_alone(self):
        drawn = [[[1], 16, "D"], [[2], 18, "D"]]
        self.assertEqual(AZONE.merge_zone_lists(drawn, []), drawn)


class TextureReplayTest(unittest.TestCase):
    def test_overlays_replay_the_saved_airport_zones(self):
        lat, lon = 22, 120
        with tempfile.TemporaryDirectory() as tmp:
            tile_dir = Path(tmp) / f"zOrtho4XP_{lat:+03d}{lon:+04d}"
            tex_dir = tile_dir / "textures"
            tex_dir.mkdir(parents=True)
            cfg = tile_dir / f"Ortho4XP_{lat:+03d}{lon:+04d}.cfg"
            base = "default_website=BI\ndefault_zl=16\nmesh_zl=19\nzone_list=[]\n"
            cfg.write_text(base, encoding="utf-8")
            assignment, _zl, _notes = TEXSEL.cfg_texture_assignment(str(tex_dir), lat, lon)
            self.assertEqual({key[3] for key in assignment}, {16})
            self.assertEqual(AZONE.read_tile_zones(str(cfg)), [])

            zones = [[c, zl, "BI"] for c, zl in AZONE.airport_rings(RCKH, DISTANCES)]
            cfg.write_text(base + f"airport_zone_list={zones}\n", encoding="utf-8")
            self.assertEqual(AZONE.read_tile_zones(str(cfg)), zones)
            assignment, _zl, _notes = TEXSEL.cfg_texture_assignment(str(tex_dir), lat, lon)
            self.assertEqual({key[3] for key in assignment}, {16, 17, 18, 19})

    def test_zones_are_saved_in_the_tile_config_apart_from_drawn_zones(self):
        self.assertIn("airport_zone_list", CFGVARS.list_tile_vars)
        self.assertNotIn("global_airport_zone_list", CFGVARS.cfg_global_tile_vars)
        self.assertNotIn("airport_zone_list", CFGVARS.list_dsf_vars)


