class RunwayLookupTest(unittest.TestCase):
    def test_highest_priority_pack_wins_and_misses_are_cached(self):
        moved = [(45.0, 22.6, 120.3, 22.6, 120.33)]
        with tempfile.TemporaryDirectory() as tmp:
            xp = _xplane(tmp, custom={"RCKH": moved}, global_airports={"RCKH": RCKH, "RCAY": RCKH})
            cache = str(Path(tmp) / "cache")
            found = AZONE.runways_by_icao(xp, ["RCKH", "RCAY", "ZZZZ"], cache_dir=cache)
            self.assertEqual(set(found), {"RCKH", "RCAY"})
            self.assertAlmostEqual(found["RCKH"][0][0], 45.0)
            self.assertAlmostEqual(found["RCAY"][0][1], RCKH[0][1], places=6)
            # The cache answers without reading apt.dat again.
            gapt = Path(xp) / "Custom Scenery" / "Airport_Custom" / "Earth nav data" / "apt.dat"
            gapt.write_text("", encoding="utf-8")
            again = AZONE.runways_by_icao(xp, ["RCKH", "ZZZZ"], cache_dir=cache)
            self.assertAlmostEqual(again["RCKH"][0][0], 45.0)
            self.assertNotIn("ZZZZ", again)

    def test_airports_are_matched_by_icao_code_not_id(self):
        with tempfile.TemporaryDirectory() as tmp:
            xp = _xplane(tmp, custom={"XRC0001": RCKH}, global_airports={"RCAY": RCKH})
            capt = Path(xp) / "Custom Scenery" / "Airport_Custom" / "Earth nav data" / "apt.dat"
            capt.write_text(
                capt.read_text(encoding="utf-8").replace(
                    "Test airport XRC0001\n", "Test airport XRC0001\n1302 icao_code RCKH\n"),
                encoding="utf-8",
            )
            gapt = Path(xp) / "Global Scenery" / "Global Airports" / "Earth nav data" / "apt.dat"
            gapt.write_text(
                gapt.read_text(encoding="utf-8").replace(
                    "Test airport RCAY\n", "Test airport RCAY\n1302 icao_code RCBS\n"),
                encoding="utf-8",
            )
            found = AZONE.runways_by_icao(xp, ["RCKH", "XRC0001", "RCAY", "RCBS"])
            self.assertEqual(set(found), {"RCKH", "RCBS"})

    def test_custom_packs_the_ini_does_not_enable_are_searched_last(self):
        moved = [(45.0, 22.6, 120.3, 22.6, 120.33)]
        with tempfile.TemporaryDirectory() as tmp:
            xp = _xplane(tmp, global_airports={"RCKH": RCKH})
            cs = Path(xp) / "Custom Scenery"
            for pack, airports in (("New_Pack", {"RCKH": moved, "RCAY": moved}),
                                   ("Off_Pack", {"RCBS": moved})):
                pdir = cs / pack / "Earth nav data"
                pdir.mkdir(parents=True)
                (pdir / "apt.dat").write_text(_apt_dat(airports), encoding="utf-8")
            ini = cs / "scenery_packs.ini"
            ini.write_text(
                ini.read_text(encoding="utf-8") + "SCENERY_PACK_DISABLED Custom Scenery/Off_Pack/\n",
                encoding="utf-8",
            )
            found = AZONE.runways_by_icao(xp, ["RCKH", "RCAY", "RCBS"])
            self.assertEqual(set(found), {"RCKH", "RCAY", "RCBS"})
            self.assertAlmostEqual(found["RCKH"][0][0], 60.0)  # Global Airports first
            self.assertAlmostEqual(found["RCAY"][0][0], 45.0)


class RingGeometryTest(unittest.TestCase):
    def test_rings_sit_at_the_configured_distance(self):
        rings = AZONE.airport_rings(RCKH, DISTANCES)
        self.assertEqual([zl for _, zl in rings], [19, 18, 17])
        for coords, zl in rings:
            self.assertEqual(coords[:2], coords[-2:])  # closed ring
            self.assertAlmostEqual(_mean_ring_distance(RCKH, coords), DISTANCES[zl], delta=20)

    def test_zero_distance_leaves_the_ring_out(self):
        rings = AZONE.airport_rings(RCKH, {19: 1600.0, 18: 0.0, 17: 9000.0})
        self.assertEqual([zl for _, zl in rings], [19, 17])

    def test_hull_spans_all_runways(self):
        crossing = RCKH + [(45.0, 22.56, 120.35, 22.59, 120.35)]
        hull, _frame = AZONE.runway_hull(crossing)
        single, _frame = AZONE.runway_hull(RCKH)
        self.assertGreater(hull.area, single.area * 10)


class PlanTest(unittest.TestCase):
    def _plan(self, tiles, icaos_by_tile, runways=None):
        runways = runways if runways is not None else {"RCKH": RCKH}
        log = []
        plan = AZONE.plan_zones(
            tiles,
            lambda lat, lon: (icaos_by_tile.get((lat, lon), []), DISTANCES),
            lambda icaos: {code: runways[code] for code in icaos if code in runways},
            log=log.append,
        )
        return plan, log

    def test_neighbours_in_the_batch_get_the_zones(self):
        # RCKH sits ~0.42 deg from the western edge of +22+120: the 14.5 km
        # ZL17 ring stays inside, so make the airport sit near the edge.
        near_edge = [(60.0, 22.97, 120.85, 22.97, 120.88)]
        tiles = [(22, 120), (23, 120), (22, 121), (21, 120)]
        plan, log = self._plan(tiles, {(22, 120): ["RCKH"]}, {"RCKH": near_edge})
        self.assertEqual([z[1] for z in plan[(22, 120)]], [19, 18, 17])
        self.assertEqual([z[1] for z in plan[(23, 120)]], [18, 17])
        self.assertEqual([z[1] for z in plan[(22, 121)]], [17])
        self.assertNotIn((21, 120), plan)
        self.assertFalse(log)

    def test_neighbours_outside_the_batch_get_nothing(self):
        near_edge = [(60.0, 22.97, 120.85, 22.97, 120.88)]
        plan, _log = self._plan([(22, 120)], {(22, 120): ["RCKH"]}, {"RCKH": near_edge})
        self.assertEqual(set(plan), {(22, 120)})

    def test_airport_listed_in_another_tile_is_skipped(self):
        plan, log = self._plan([(22, 120), (23, 120)], {(23, 120): ["RCKH"]})
        self.assertEqual(plan, {})
        self.assertTrue(any("RCKH is not in tile +23+120" in line for line in log))

    def test_airport_without_runways_is_skipped(self):
        plan, log = self._plan([(22, 120)], {(22, 120): ["ZZZZ"]})
        self.assertEqual(plan, {})
        self.assertTrue(any("ZZZZ" in line for line in log))


