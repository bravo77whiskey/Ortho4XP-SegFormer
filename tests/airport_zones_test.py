def _apt_dat(airports):
    """apt.dat text: {icao: [(width, lat1, lon1, lat2, lon2)]}."""
    lines = ["I", "1200 Generated by test", ""]
    for icao, runways in airports.items():
        lines.append(f"1 10 0 0 {icao} Test airport {icao}")
        for width, lat1, lon1, lat2, lon2 in runways:
            lines.append(
                f"100 {width:.2f} 1 0 0.25 0 2 1 09 {lat1:.8f} {lon1:.8f} 0 0 3 0 0 0 "
                f"27 {lat2:.8f} {lon2:.8f} 0 0 3 0 0 0"
            )
        lines.append("110 1 0.25 0 Taxiway")
        lines.append(f"111 {runways[0][1]:.8f} {runways[0][2]:.8f}")
        lines.append("")
    lines.append("99")
    return "\n".join(lines) + "\n"


def _xplane(tmp, custom=None, global_airports=None):
    """A fake X-Plane folder: one custom pack (listed first) and the global apt.dat."""
    root = Path(tmp) / "X-Plane 12"
    gdir = root / "Global Scenery" / "Global Airports" / "Earth nav data"
    gdir.mkdir(parents=True)
    (gdir / "apt.dat").write_text(_apt_dat(global_airports or {}), encoding="utf-8")
    cs = root / "Custom Scenery"
    cs.mkdir()
    packs = ["I", "1000 Version", "SCENERY", ""]
    if custom:
        pdir = cs / "Airport_Custom" / "Earth nav data"
        pdir.mkdir(parents=True)
        (pdir / "apt.dat").write_text(_apt_dat(custom), encoding="utf-8")
        packs.append("SCENERY_PACK Custom Scenery/Airport_Custom/")
    packs.append("SCENERY_PACK *GLOBAL_AIRPORTS*")
    (cs / "scenery_packs.ini").write_text("\n".join(packs) + "\n", encoding="utf-8")
    return str(root)


def _mean_ring_distance(runways, coords):
    """Mean distance (m) from the runway hull to points along a ring."""
    from shapely.geometry import LineString

    hull, (lat0, lon0, kx, ky) = AZONE.runway_hull(runways)
    ring = LineString(
        [((lon - lon0) * kx, (lat - lat0) * ky) for lat, lon in zip(coords[::2], coords[1::2])]
    )
    n = 400
    return sum(
        hull.distance(ring.interpolate(i / n, normalized=True)) for i in range(n)
    ) / n


