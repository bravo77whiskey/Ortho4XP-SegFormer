def paint_lobby(albedo, gloss_draw, strip, palette, pattern, sprites,
                flavor, group, page, seed, size):
    """Entrance band: glazing bays + entrance sprite + canopy line."""
    rng = random.Random(stable_u32(seed, flavor, group, page, "lobby",
                                   strip["px"][0]))
    y0, y1, gutter, ppm_x, ppm_y = _strip_geom(strip, size)
    top, bottom = y0 + gutter, y1 - gutter
    lobby = palette.get("lobby", (66, 74, 82))
    draw = ImageDraw.Draw(albedo)
    n_bays = max(4, int(round(float(strip["world_w_m"]) / 5.0)))
    entrance = sprites.get(("entrance_apt", flavor, group))
    glazing = sprites.get(("window_office", flavor, group))
    door_bay = rng.randrange(n_bays)
    canopy_y = top + int(0.5 * ppm_y)
    for b in range(n_bays):
        x0 = int(round(b * size / n_bays))
        x1 = int(round((b + 1) * size / n_bays))
        pier = max(2, int(0.35 * ppm_x))
        gx0, gx1 = x0 + pier, x1 - pier
        if gx1 <= gx0:
            continue
        if b == door_bay and entrance is not None:
            paste_sprite(albedo, entrance, (gx0, top, gx1, bottom),
                         lobby, 0.18, SPRITE_SOFTEN)
            darken_glass(albedo, (gx0, top, gx1, bottom),
                         dark_glass_color(palette), LOBBY_OVERLAY_ALPHA)
            add_gloss_rect(gloss_draw, (gx0, top, gx1, bottom),
                           atlas.GLOSS_DOOR_GLASS)
        elif glazing is not None:
            paste_sprite(albedo, glazing, (gx0, canopy_y + 2, gx1, bottom),
                         lobby, 0.25, SPRITE_SOFTEN)
            darken_glass(albedo, (gx0, canopy_y + 2, gx1, bottom),
                         dark_glass_color(palette), LOBBY_OVERLAY_ALPHA)
            add_gloss_rect(gloss_draw, (gx0, canopy_y + 2, gx1, bottom),
                           atlas.GLOSS_GLASS)
        else:
            # Painted glazing fallback until the sprite exists.
            grad_top = tuple(min(255, c + 16) for c in lobby) + (255,)
            draw.rectangle((gx0, canopy_y + 2, gx1, bottom), fill=grad_top)
            add_gloss_rect(gloss_draw, (gx0, canopy_y + 2, gx1, bottom),
                           atlas.GLOSS_GLASS)
    # Canopy: deterministic full-width band.
    canopy_h = max(2, int(0.12 * ppm_y))
    draw.rectangle((0, canopy_y - canopy_h, size - 1, canopy_y),
                   fill=(58, 58, 58, 255))
    draw.line((0, canopy_y + 1, size, canopy_y + 1),
              fill=(150, 150, 150, 255), width=1)


