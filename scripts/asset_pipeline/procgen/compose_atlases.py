def stabilize_band_edges(arr, y0, y1, gutter):
    band = arr[y0:y1].astype(np.float32)
    if band.shape[0] <= 2 * gutter + 4:
        interior = band.reshape(-1, 3).mean(axis=0)
    else:
        interior = band[gutter:-gutter].reshape(-1, 3).mean(axis=0)
    band[:2] = interior
    band[-2:] = interior
    for k in range(2, min(8, band.shape[0] // 2)):
        t = (k - 1) / 7.0
        band[k] = band[k] * t + interior * (1.0 - t)
        band[-k - 1] = band[-k - 1] * t + interior * (1.0 - t)
    band[:, -1, :] = band[:, 0, :]
    arr[y0:y1] = np.clip(np.rint(band), 0, 255).astype(np.uint8)


def stabilize_row_chroma(arr, y0, y1, strength=0.9):
    band = arr[y0:y1].astype(np.float32)
    if band.size == 0:
        return
    rg = band[..., 0] - band[..., 1]
    bg = band[..., 2] - band[..., 1]
    row_rg = rg.mean(axis=1)
    row_bg = bg.mean(axis=1)
    band[..., 0] += (float(rg.mean()) - row_rg)[:, None] * strength
    band[..., 2] += (float(bg.mean()) - row_bg)[:, None] * strength
    arr[y0:y1] = np.clip(np.rint(band), 0, 255).astype(np.uint8)


def base_gloss_for_strip(name, kind, pattern):
    if kind == "roof":
        if name == "roof_tile":
            return (atlas.GLOSS_BASE["roof_tile_glazed"]
                    if pattern.get("tile_gloss")
                    else atlas.GLOSS_BASE["roof_tile"])
        return atlas.GLOSS_BASE.get(name, atlas.GLOSS_BASE["wall"])
    return atlas.GLOSS_BASE.get(kind, atlas.GLOSS_BASE["wall"])


def strip_family(name, kind):
    """(family, shade_index) for a strip name."""
    shade_map = {"a": 0, "b": 1, "c": 2}
    if kind in ("wall", "glass", "plain"):
        parts = name.split("_")
        family = parts[1]
        shade = shade_map.get(parts[2], 0) if len(parts) > 2 else 0
        return family, shade
    if kind == "ground":
        return name.split("_")[1], 0
    if kind in ("storefront", "roller", "lobby", "balcony", "highband"):
        return "concrete", 0
    if kind == "trim":
        return "trim", 0
    return name, 0


def material_base_for(name, kind, family, group, flavor, shade,
                      sources: Sources):
    """Source base for a strip's underlying material photo."""
    if kind == "roof":
        return MATERIAL_SOURCES.get(name, "roof_flat")
    if kind == "trim":
        return "trim_wood"
    if family == "curtain":
        if shade == 1 and sources.has("curtain_wall_dark"):
            return "curtain_wall_dark"
        return "curtain_wall"
    if family == "panel" and shade == 1 and flavor == "asia" \
            and sources.has("mosaic_wall", flavor, group):
        return "mosaic_wall"
    override = GROUP_MATERIAL_OVERRIDES.get((group, family))
    if override:
        for base in override:
            if sources.has(base, flavor, group):
                return base
    return MATERIAL_SOURCES.get(family, "concrete_wall")


def compose_page(flavor, group, page, sub_layout, references, sources,
                 sprites, seed):
    size = int(sub_layout["size"])
    palette = atlas.combo_page_palette(flavor, group, page)
    pattern = atlas.pattern_for_combo(flavor, group, references, page)
    img = Image.new("RGBA", (size, size), (128, 128, 128, 255))
    gloss = Image.new("L", (size, size), atlas.GLOSS_BASE["wall"])
    gloss_draw = ImageDraw.Draw(gloss)
    gutter = max(1, int(round(atlas.GUTTER_PX * (size / 2048.0))))

    # curtain_wall_dark spans like curtain_wall.
    SOURCE_SPAN_Y_M.setdefault("curtain_wall_dark", 3.2)
    MATERIAL_CONTRAST.setdefault("curtain_wall_dark", 0.60)
    SHIFT_REPEATS.setdefault("curtain_wall_dark", False)

    for name, strip in sorted(sub_layout["strips"].items(),
                              key=lambda item: item[1]["px"][0]):
        kind = strip["kind"]
        y0, y1 = strip["px"]
        family, shade = strip_family(name, kind)
        mat_base = material_base_for(name, kind, family, group, flavor,
                                     shade, sources)
        src, span_base, regional = sources.get_material(mat_base, flavor,
                                                        group)
        if kind == "roof":
            target = palette_color(palette, name, 0)
        elif family == "trim":
            target = palette_color(palette, "trim", 0)
        elif family in palette:
            target = palette_color(palette, family, shade)
        else:
            target = palette_color(palette, "concrete", shade)
        rng = random.Random(stable_u32(seed, flavor, group, page, name,
                                       "material"))
        band = tile_material(src, strip, span_base, size, target, rng,
                             regional, flavor)
        band = apply_unit_banding(band, strip, family, palette, pattern,
                                  rng, regional, size)
        grime_base = float(pattern.get("grime", 0.0))
        if page == 1:
            grunge_strength = 0.28 + grime_base * 0.22
        elif page == 2:
            grunge_strength = 0.04 + grime_base * 0.04
            band = np.clip(band * 1.04 + 3.0, 0, 255)
        else:
            grunge_strength = 0.10 + grime_base * 0.08
        if kind in ("roof", "trim", "glass"):
            grunge_strength *= 0.35
        grunge_strength *= float(
            (FLAVOR_DIRT.get(flavor) or {}).get("grunge_scale", 1.0))
        if flavor in CLEAN_FLAVORS:
            # Clean flavors NEVER get the grunge overlay: the page-1
            # formula has a constant 0.28 floor even at grime=0, which is
            # exactly how asia grime kept coming back.
            grunge_strength = 0.0
        band = apply_grunge(band, sources.images["grunge"], grunge_strength,
                            rng)
        # Row-chroma stabilization BEFORE sprites (post-sprite runs paint
        # broad chroma zones across window/sill lines).
        band_u8 = np.clip(np.rint(band), 0, 255).astype(np.uint8)
        stabilize_row_chroma(band_u8, 0, band_u8.shape[0], 0.92)
        img.alpha_composite(
            Image.fromarray(band_u8, "RGB").convert("RGBA"), (0, y0))
        add_gloss_rect(gloss_draw, (0, y0, size - 1, y1 - 1),
                       base_gloss_for_strip(name, kind, pattern))

        if kind == "wall":
            paint_wall_openings(img, gloss_draw, strip, family, flavor,
                                group, page, palette, pattern, sprites,
                                sources, seed, size)
        elif kind == "glass":
            paint_curtain_overlay(img, gloss_draw, strip, palette, pattern,
                                  flavor, group, page, seed, size, shade)
        elif kind == "ground":
            paint_wall_openings(img, gloss_draw, strip, family, flavor,
                                group, page, palette, pattern, sprites,
                                sources, seed, size, ground=True)
        elif kind == "storefront":
            paint_storefront(img, gloss_draw, strip, palette, pattern,
                             sprites, sources, flavor, group, page, seed,
                             size, variant_b=name.endswith("_b"))
        elif kind == "lobby":
            paint_lobby(img, gloss_draw, strip, palette, pattern, sprites,
                        flavor, group, page, seed, size)
        elif kind == "roller":
            paint_roller(img, gloss_draw, strip, palette, pattern, sprites,
                         flavor, group, page, seed, size,
                         dock=name.endswith("_dock"))
        elif kind == "balcony":
            paint_balcony_band(img, gloss_draw, strip, palette, pattern,
                               sprites, flavor, group, page, seed, size)
        elif kind == "highband":
            paint_highband(img, gloss_draw, strip, palette, pattern,
                           sprites, flavor, group, page, seed, size)

    rgb = np.asarray(img.convert("RGB"), dtype=np.uint8).copy()
    for strip in sub_layout["strips"].values():
        stabilize_band_edges(rgb, int(strip["px"][0]), int(strip["px"][1]),
                             gutter)
    return Image.fromarray(rgb, "RGB"), gloss


def compose(output: Path, sources_dir: Path, combos, layout_path: Path,
            pages: int, seed: int) -> None:
    with layout_path.open("r", encoding="utf-8") as fh:
        layout = json.load(fh)
    if int(layout.get("version", 1)) < 2:
        raise SystemExit("atlas_layout.json is pre-overhaul; run atlas.py")
    references = atlas._load_reference_styles()
    sources = Sources(sources_dir)
    sprites = build_sprites(sources)
    textures = output / "textures"
    textures.mkdir(parents=True, exist_ok=True)
    for key in combos:
        flavor, group = key.split("/")
        sub = layout["combos"][key]
        for page in range(pages):
            print(f"compositing {key} page {page + 1}/{pages}", flush=True)
            albedo, gloss = compose_page(flavor, group, page, sub,
                                         references, sources, sprites, seed)
            name = atlas.texture_name(flavor, group, page)
            # Adaptive-palette save: full 4096 res at ~1-2 MB on disk.
            albedo.quantize(
                colors=QUANT_COLORS, method=Image.Quantize.FASTOCTREE,
            ).save(textures / name, optimize=True)
            normal = atlas.build_normal_map(gloss, NML_SIZE)
            normal.save(textures / f"{name[:-4]}_nml.png", compress_level=6)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True,
                        help="Library package folder; PNGs land in textures/.")
    parser.add_argument("--sources", default=str(DEFAULT_SOURCES))
    parser.add_argument("--layout",
                        default=str(HERE / "atlas_layout.json"))
    parser.add_argument("--combos", default=None,
                        help="Comma-separated flavor/group keys "
                             "(default: all 32).")
    parser.add_argument("--pages", type=int, default=3)
    parser.add_argument("--seed", type=int, default=101)
    args = parser.parse_args(argv)
    if args.combos:
        combos = [c.strip() for c in args.combos.split(",") if c.strip()]
    else:
        combos = [combo_key(f, g) for f in FLAVORS for g in GROUPS]
    compose(Path(args.output), Path(args.sources), combos,
            Path(args.layout), max(1, args.pages), args.seed)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
