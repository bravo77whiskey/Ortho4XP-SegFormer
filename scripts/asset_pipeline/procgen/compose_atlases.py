def _strip_geom(strip, size):
    gutter = max(1, int(round(atlas.GUTTER_PX * (size / 2048.0))))
    y0, y1 = strip["px"]
    ppm_x = size / float(strip["world_w_m"])
    ppm_y = (y1 - y0 - 2 * gutter) / float(strip["world_h_m"])
    return y0, y1, gutter, ppm_x, ppm_y


